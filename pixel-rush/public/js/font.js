const ACC = { 'Á': 'A', 'À': 'A', 'Ã': 'A', 'Â': 'A', 'É': 'E', 'Ê': 'E', 'Í': 'I', 'Ó': 'O', 'Ô': 'O', 'Õ': 'O', 'Ú': 'U', 'Ç': 'C', 'Ü': 'U' };
const glyphs = {};
for (const [k, v] of Object.entries(G)) glyphs[k] = v.split('|');

export function textWidth(str, scale = 1) { return str.length * 6 * scale - scale; }

export function drawText(ctx, str, x, y, color = '#fff', scale = 1, shadow = '#000') {
  str = String(str).toUpperCase();
  if (shadow) drawRaw(ctx, str, x + scale, y + scale, shadow, scale);
  drawRaw(ctx, str, x, y, color, scale);
}

function drawRaw(ctx, str, x, y, color, s) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch0 of str) {
    const ch = ACC[ch0] || ch0;
    const g = glyphs[ch] || (ch === 'X' ? glyphs.X : null);
    if (g) {
      for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '#') ctx.fillRect(cx + c * s, cy + r * s, s, s);
    }
    cx += 6 * s;
  }
}

export function drawTextCentered(ctx, str, cx, y, color, scale = 1, shadow = '#000') {
  drawText(ctx, str, Math.round(cx - textWidth(String(str), scale) / 2), y, color, scale, shadow);
}
